export type SalesChannelCatalogEntry = (typeof SALES_CHANNEL_CATALOG)[number];

const channelKey = (value: string): string => value
  .replace(/\u00a0/g, ' ')
  .trim()
  .normalize('NFC')
  .toLocaleUpperCase('es')
  .replace(/\s+/g, '_');

const CHANNEL_ALIASES: Record<string, string> = {
  [channelKey('CALL CENTER - VIP')]: 'CALL_CENTER_VIP',
};

const catalogByKey = new Map(SALES_CHANNEL_CATALOG.map((entry) => [channelKey(entry.channel), entry]));

function catalogEntry(value: string | null | undefined): SalesChannelCatalogEntry | null {
  if (value == null || value.trim() === '') return null;
  const rawKey = channelKey(value);
  const canonical = CHANNEL_ALIASES[rawKey] ?? rawKey;
  return catalogByKey.get(channelKey(canonical)) ?? null;
}

/** Etiqueta canónica del catálogo; conserva valores nuevos que aún no estén catalogados. */
export function salesChannelLabel(value: string | null | undefined): string | null {
  if (value == null || value.trim() === '') return null;
  return catalogEntry(value)?.channel ?? value.replace(/\u00a0/g, ' ').trim();
}

/** País asociado en el catálogo, solo como referencia descriptiva del canal. */
export function salesChannelCountry(value: string | null | undefined): string | null {
  return catalogEntry(value)?.country ?? null;
}

/** Muestra el canal de venta y, si está en el catálogo, el país asociado a ese canal. */
export function salesChannelDisplay(value: string | null | undefined): string {
  const channel = salesChannelLabel(value);
  if (!channel) return 'No reportado';
  const country = salesChannelCountry(value);
  return country ? `${channel} · ${country}` : channel;
}

/** Canales del catálogo primero; conserva también valores nuevos vistos en Flokzu. */
export function salesChannelOptions(observed: readonly string[]): string[] {
  const known = new Set<string>(SALES_CHANNEL_CATALOG.map((entry) => entry.channel));
  const extras = [...new Set(observed.filter((value) => catalogEntry(value) === null && !known.has(value)))];
  return [...SALES_CHANNEL_CATALOG.map((entry) => entry.channel), ...extras];
}

/** Valores históricos equivalentes para que el filtro canónico encuentre registros previos. */
export function salesChannelFilterValues(value: string): string[] {
  const entry = catalogEntry(value);
  if (!entry) return [value];
  const values: string[] = [entry.channel];
  if (entry.channel === 'CALL_CENTER_VIP') values.push('CALL CENTER - VIP');
  if (entry.channel === 'UTEL_-_EMPRESARIAL') values.push('UTEL - EMPRESARIAL');
  return values;
}
